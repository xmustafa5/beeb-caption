import { toLocalPhoneInput } from './phone'

describe('toLocalPhoneInput', () => {
  it.each([
    ['07701234567', '07701234567'],
    ['7701234567', '7701234567'],
    ['9647701234567', '07701234567'],
    ['+964 770 123 4567', '07701234567'],
    ['00964 770 123 4567', '07701234567'],
    ['+964 0770 123 4567', '07701234567'],
    ['٠٧٧٠١٢٣٤٥٦٧', '07701234567'],
    ['0770123456789', '07701234567'],
  ])('%s → %s', (input, expected) => {
    expect(toLocalPhoneInput(input)).toBe(expected)
  })
})
